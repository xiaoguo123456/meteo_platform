import assert from 'node:assert/strict';
import { axisTicks, beijingDate, dayBreaks, dayIndexes, hourLabel, nearestIndex } from '../src/stationTime';
const hours=(start:string,count:number)=>Array.from({length:count},(_,i)=>new Date(Date.parse(start)+i*3600e3).toISOString());
const week=hours('2026-10-21T00:00+08:00',168);
assert.equal(hourLabel('2026-10-22T21:00+08:00'),'10/22 21时');
assert.equal(hourLabel('2026-10-22T13:00Z'),'10/22 21时','UTC 时间也按北京时间显示');
assert.equal(hourLabel('2026-10-22T16:00Z'),'10/23 00时','UTC 16 点是北京次日 0 点');
assert.equal(hourLabel(null),'—');
assert.equal(beijingDate('2026-10-21T23:59+08:00'),'2026-10-21');
const day2=dayIndexes(week,'2026-10-22');
assert.equal(day2.length,24);assert.equal(day2[0],24);assert.equal(hourLabel(week[day2[23]]),'10/22 23时');
assert.deepEqual(dayIndexes(week,'2026-11-01'),[]);
assert.deepEqual(dayBreaks(week.slice(0,24)),[],'同一天内没有分界');
const cross=hours('2026-10-21T21:00+08:00',48);
assert.deepEqual(dayBreaks(cross),[3,27],'跨天处给出分界下标');
const ticks=axisTicks(cross);
assert.equal(ticks[0].label,'10/21 21时');assert.equal(ticks.at(-1)!.label,'10/23 20时');
assert.ok(ticks.some(t=>t.index===3&&t.label==='10/22 00时'&&!t.minor),'分界点必须有完整日期刻度');
assert.deepEqual(axisTicks(week.slice(24,48)).map(t=>t.label),['10/22 00时','10/22 06时','10/22 12时','10/22 18时','10/22 23时']);
assert.equal(nearestIndex(week,'2026-10-21T21:45+08:00'),22);
assert.equal(nearestIndex(week,null),0);
console.log('通过：北京时间标签、按日切片、跨天分界、坐标刻度和当前时刻定位');
